/**
 * 업종별 랜딩.
 *
 * ── 왜 블로그 글이 아니라 별도 라우트인가 ────────────────────────────────
 * "볼링장 적립", "미용실 쿠폰 관리"처럼 업종 + 문제로 검색하는 사람은 읽을거리를
 * 찾는 게 아니라 **자기 업종에 맞는지**를 확인하러 온다. 이 사람에게 필요한 건
 * 도입부 세 문단이 아니라 "네, 됩니다"와 그 근거다. 그래서 글이 아니라 랜딩의
 * 변형으로 만들고, CTA를 위에 둔다.
 *
 * ── 지어내지 말 것 ───────────────────────────────────────────────────────
 * `proof`는 실제 도입 매장이 있을 때만 채운다. 없으면 비워 두면 화면에서 그
 * 블록이 통째로 빠진다. "많은 볼링장에서 쓰고 있습니다" 류의 문장은 영업 나가서
 * "어디요?"라는 질문을 받는 순간 신뢰를 통째로 잃는다.
 */

export type Industry = {
  slug: string;
  /** "볼링장" — 문장 안에 그대로 들어간다. */
  label: string;
  /** 검색 결과 제목. 업종어를 앞에 둔다. */
  title: string;
  description: string;
  /** 히어로 한 줄. 이 업종이 겪는 문제를 그대로 말한다. */
  headline: string;
  /** AEO용 즉답. "볼링장에서 포인토를 쓸 수 있나요?"에 대한 답. */
  answer: string;
  /** 이 업종에서 무엇을 한 개로 세는가. */
  unit: string;
  /** 권장 적립 방식과 그 이유. */
  recommend: { mode: "스탬프" | "포인트"; reason: string };
  /** 이 업종이 실제로 겪는 문제 세 가지. */
  pains: string[];
  /** 포인토로 바뀌는 것. pains와 개수를 맞춘다. */
  gains: string[];
  faq: FaqEntry[];
  /**
   * 실제 도입 실적. **실측치만 적는다.**
   * 값은 앱 리포의 `node scripts/landing-stats.mjs`로 확인한다.
   */
  proof?: { line: string; measuredAt: string };
};

