/** 1513 → "1,513" */
export const withComma = (n: number) => n.toLocaleString("ko-KR");

/**
 * 36000 → "3만 6천". 큰 수를 한국어식으로 줄인다.
 *
 * 랜딩 지표 자리는 세 칸이 나란히 서 있어서 폭이 조금만 넘쳐도 줄이 깨진다.
 * "36,000건"은 그 자리에 안 들어가고, 무엇보다 내림한 값이라 정확한 척하는
 * 표기가 어울리지 않는다. "3만 6천"은 짧으면서 어림수라는 게 드러난다.
 */
export const toManCheon = (n: number) => {
  const man = Math.floor(n / 10000);
  const cheon = Math.floor((n % 10000) / 1000);
  if (man === 0) return `${cheon}천`;
  return cheon === 0 ? `${man}만` : `${man}만 ${cheon}천`;
};
